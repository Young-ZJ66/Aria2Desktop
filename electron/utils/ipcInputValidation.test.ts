describe('sanitizeSettingsInput 顶层键完整性', () => {
  it('AppSettings 的每个顶层键都能被保留（不再静默丢字段）', () => {
    const sanitized = sanitizeSettingsInput(fullSettings())
    // 以 settingsSync 的白名单（有编译期守护，必须与 AppSettings 一致）为准
    expect(Object.keys(sanitized).sort()).toEqual([...ALLOWED_SETTINGS_KEYS].sort())
  })

  it('queue 的重试策略原样保留', () => {
    const sanitized = sanitizeSettingsInput(fullSettings())
    expect(sanitized.queue).toEqual({ maxConcurrent: 4, retryEnabled: true, retryMaxAttempts: 5, retryDelaySeconds: 60 })
  })

  it('taskTemplates 保留凭据字段（cookie/headers）与代理设置', () => {
    const sanitized = sanitizeSettingsInput(fullSettings())
    expect(sanitized.taskTemplates).toEqual(fullSettings().taskTemplates)
  })

  it('completionRules 保留 webhook 签名密钥与全部动作类型', () => {
    const sanitized = sanitizeSettingsInput(fullSettings())
    expect(sanitized.completionRules).toEqual(fullSettings().completionRules)
  })

  it('webConsole 保留主令牌、细粒度令牌与 TLS 路径', () => {
    const sanitized = sanitizeSettingsInput(fullSettings())
    expect(sanitized.webConsole).toEqual(fullSettings().webConsole)
  })

  it('pluginMarket 与 trustedPluginPublishers 原样保留', () => {
    const sanitized = sanitizeSettingsInput(fullSettings())
    expect(sanitized.pluginMarket).toEqual(fullSettings().pluginMarket)
    expect(sanitized.trustedPluginPublishers).toEqual(fullSettings().trustedPluginPublishers)
  })

  it('只提交部分键时其余键不会凭空出现', () => {
    const sanitized = sanitizeSettingsInput({ language: 'en-US', queue: { retryEnabled: true } })
    expect(sanitized).toEqual({ language: 'en-US', queue: { retryEnabled: true } })
  })
})

describe('sanitizeSettingsInput 未知字段与非法输入', () => {
  it('未知顶层键被丢弃', () => {
    const sanitized = sanitizeSettingsInput({ language: 'en-US', evilKey: { payload: 'x' } })
    expect(sanitized).toEqual({ language: 'en-US' })
    expect('evilKey' in sanitized).toBe(false)
  })

  it('未知嵌套字段被丢弃', () => {
    const sanitized = sanitizeSettingsInput({ queue: { retryEnabled: true, injected: 'x' } })
    expect(sanitized.queue).toEqual({ retryEnabled: true })
  })

  it('settings 不是对象时拒绝', () => {
    expect(() => sanitizeSettingsInput(null)).toThrow()
    expect(() => sanitizeSettingsInput([])).toThrow()
    expect(() => sanitizeSettingsInput('settings')).toThrow()
  })

  it('类型错误整包拒绝（不静默丢字段）', () => {
    expect(() => sanitizeSettingsInput({ theme: 'blue' })).toThrow()
    expect(() => sanitizeSettingsInput({ queue: 'nope' })).toThrow()
    expect(() => sanitizeSettingsInput({ queue: { maxConcurrent: '5' } })).toThrow()
    expect(() => sanitizeSettingsInput({ queue: { maxConcurrent: 99 } })).toThrow()
    expect(() => sanitizeSettingsInput({ taskTemplates: {} })).toThrow()
    expect(() => sanitizeSettingsInput({ taskTemplates: [{ name: '缺 id' }] })).toThrow()
    expect(() => sanitizeSettingsInput({ completionRules: [{ id: 'r', name: 'n', enabled: 'yes', actions: [] }] })).toThrow()
    expect(() => sanitizeSettingsInput({ completionRules: [{ id: 'r', name: 'n', enabled: true, actions: [{ type: 'nope' }] }] })).toThrow()
    expect(() => sanitizeSettingsInput({ webConsole: { tokens: [{ id: 'a', name: 'b', token: 'c', scopes: ['root'] }] } })).toThrow()
    expect(() => sanitizeSettingsInput({ webConsole: { port: 80 } })).toThrow()
    expect(() => sanitizeSettingsInput({ pluginMarket: { registryUrl: 'file:///etc/passwd' } })).toThrow()
    // 解析即抛错的地址（new URL 直接 throw）走「必须是合法 URL」分支
    expect(() => sanitizeSettingsInput({ pluginMarket: { registryUrl: 'http://[' } })).toThrow()
    expect(() => sanitizeSettingsInput({ trustedPluginPublishers: ['ok', 42] })).toThrow()
  })

  it('completionRules 的 webhook URL 只允许 http/https', () => {
    const base = { id: 'r', name: 'n', enabled: true }
    expect(() =>
      sanitizeSettingsInput({ completionRules: [{ ...base, actions: [{ type: 'webhook', url: 'javascript:alert(1)' }] }] })
    ).toThrow()
    const ok = sanitizeSettingsInput({
      completionRules: [{ ...base, actions: [{ type: 'webhook', url: 'https://example.com/hook' }] }]
    })
    expect(ok.completionRules?.[0]?.actions[0]).toEqual({ type: 'webhook', url: 'https://example.com/hook' })
  })

  it('超长字符串被拒绝（防撑爆 electron-store）', () => {
    expect(() => sanitizeSettingsInput({ webConsole: { token: 'x'.repeat(513) } })).toThrow()
    expect(() => sanitizeSettingsInput({ trustedPluginPublishers: ['x'.repeat(4097)] })).toThrow()
  })

  it('数组条数上限生效', () => {
    const tooMany = Array.from({ length: 101 }, (_, index) => ({ id: 't' + index, name: 'n' }))
    expect(() => sanitizeSettingsInput({ taskTemplates: tooMany })).toThrow()
  })
})

describe('sanitizeWindowStateInput', () => {
  it('合法的窗口状态原样保留', () => {
    const input = { bounds: { x: 10, y: 20, width: 1280, height: 800 }, isMaximized: true, isFullScreen: false }
    expect(sanitizeWindowStateInput(input)).toEqual(input)
  })

  it('只给部分字段时不会凭空补其它键', () => {
    expect(sanitizeWindowStateInput({ isMaximized: true })).toEqual({ isMaximized: true })
  })

  it('空对象是合法的（窗口还没被移动过）', () => {
    expect(sanitizeWindowStateInput({})).toEqual({})
  })

  it('bounds 不是对象时返回 null', () => {
    expect(sanitizeWindowStateInput({ bounds: 'big' })).toBeNull()
    expect(sanitizeWindowStateInput({ bounds: [1, 2, 3, 4] })).toBeNull()
  })

  it('bounds 缺字段或类型不对时返回 null（不吞成 0）', () => {
    expect(sanitizeWindowStateInput({ bounds: { x: 1, y: 2, width: 100 } })).toBeNull()
    expect(sanitizeWindowStateInput({ bounds: { x: 1, y: 2, width: '100', height: 100 } })).toBeNull()
    expect(sanitizeWindowStateInput({ bounds: { x: 1.5, y: 2, width: 100, height: 100 } })).toBeNull()
  })

  it('尺寸越界（小于最小值 / 超过 20000）时返回 null', () => {
    expect(sanitizeWindowStateInput({ bounds: { x: 0, y: 0, width: 99, height: 800 } })).toBeNull()
    expect(sanitizeWindowStateInput({ bounds: { x: 0, y: 0, width: 1280, height: 20001 } })).toBeNull()
  })

  it('坐标越界时返回 null', () => {
    expect(sanitizeWindowStateInput({ bounds: { x: -100001, y: 0, width: 1280, height: 800 } })).toBeNull()
    expect(sanitizeWindowStateInput({ bounds: { x: 0, y: 100001, width: 1280, height: 800 } })).toBeNull()
  })

  it('布尔字段类型不对时返回 null', () => {
    expect(sanitizeWindowStateInput({ isMaximized: 'yes' })).toBeNull()
    expect(sanitizeWindowStateInput({ isFullScreen: 1 })).toBeNull()
  })

  it('输入不是对象时返回 null', () => {
    expect(sanitizeWindowStateInput(null)).toBeNull()
    expect(sanitizeWindowStateInput([])).toBeNull()
    expect(sanitizeWindowStateInput('window')).toBeNull()
  })
})

describe('sanitizeTaskSourcesInput', () => {
  it('三种来源都保留结构并补 createdAt', () => {
    const out = sanitizeTaskSourcesInput({
      'g1': { source: { kind: 'uri', uris: ['https://example.com/a.zip'] } },
      'g2': { source: { kind: 'torrent', torrent: 'base64-torrent', uris: ['https://example.com/b'] } },
      'g3': { source: { kind: 'metalink', metalink: '<metalink/>' } }
    })
    expect(out?.g1).toEqual({ source: { kind: 'uri', uris: ['https://example.com/a.zip'] }, createdAt: expect.any(Number) })
    expect((out?.g2 as { source: { kind: string, uris: string[] } }).source.uris).toEqual(['https://example.com/b'])
    expect((out?.g3 as { source: { kind: string } }).source.kind).toBe('metalink')
  })

  it('torrent 不带 uris 时不会凭空补空数组', () => {
    const out = sanitizeTaskSourcesInput({ g1: { source: { kind: 'torrent', torrent: 'x' } } })
    expect((out?.g1 as { source: Record<string, unknown> }).source).toEqual({ kind: 'torrent', torrent: 'x' })
  })

  it('保留合法的 createdAt 与 options，丢弃非法项', () => {
    const out = sanitizeTaskSourcesInput({
      g1: {
        source: { kind: 'uri', uris: ['https://example.com/a'] },
        createdAt: 1_700_000_000_000,
        options: { dir: 'D:/Downloads', 'max-connection-per-server': '16', bad: 42 }
      }
    })
    expect(out?.g1).toEqual({
      source: { kind: 'uri', uris: ['https://example.com/a'] },
      createdAt: 1_700_000_000_000,
      options: { dir: 'D:/Downloads', 'max-connection-per-server': '16' }
    })
  })

  it('非法 createdAt 回落成当前时间', () => {
    const before = Date.now()
    const out = sanitizeTaskSourcesInput({ g1: { source: { kind: 'uri', uris: ['https://a'] }, createdAt: 'yesterday' } })
    const createdAt = (out?.g1 as { createdAt: number }).createdAt
    expect(createdAt).toBeGreaterThanOrEqual(before)
  })

  it('未知 kind、缺 source、非对象的条目被跳过而不是整包拒绝', () => {
    const out = sanitizeTaskSourcesInput({
      good: { source: { kind: 'uri', uris: ['https://a'] } },
      badKind: { source: { kind: 'ftp', uris: [] } },
      noSource: { createdAt: 1 },
      notRecord: 'nope',
      '': { source: { kind: 'uri', uris: ['https://a'] } }
    })
    expect(Object.keys(out ?? {})).toEqual(['good'])
  })

  it('gid 超过 128 字符时跳过', () => {
    const out = sanitizeTaskSourcesInput({ ['g'.repeat(129)]: { source: { kind: 'uri', uris: ['https://a'] } } })
    expect(out).toEqual({})
  })

  it('options 只保留字符串值且最多 200 项', () => {
    const options: Record<string, unknown> = {}
    for (let index = 0; index < 250; index += 1) options['k' + index] = 'v'
    options.bad = 1
    const out = sanitizeTaskSourcesInput({ g1: { source: { kind: 'uri', uris: ['https://a'] }, options } })
    const kept = (out?.g1 as { options: Record<string, string> }).options
    expect(Object.keys(kept)).toHaveLength(200)
    expect('bad' in kept).toBe(false)
  })

  it('条目超过 2000 时整包拒绝', () => {
    const input: Record<string, unknown> = {}
    for (let index = 0; index < 2001; index += 1) input['g' + index] = { source: { kind: 'uri', uris: ['https://a'] } }
    expect(sanitizeTaskSourcesInput(input)).toBeNull()
  })

  it('输入不是对象时返回 null', () => {
    expect(sanitizeTaskSourcesInput(null)).toBeNull()
    expect(sanitizeTaskSourcesInput([])).toBeNull()
  })
})

describe('isSafeHttpUrl', () => {
  it('http/https 且无凭据的地址放行', () => {
    expect(isSafeHttpUrl('https://example.com/a.zip')).toBe(true)
    expect(isSafeHttpUrl('http://127.0.0.1:8080/file')).toBe(true)
  })

  it('带用户名或密码的地址拒绝（凭据会泄漏进日志）', () => {
    expect(isSafeHttpUrl('https://user:pass@example.com/a')).toBe(false)
    expect(isSafeHttpUrl('https://user@example.com/a')).toBe(false)
  })

  it('非 http(s) 协议拒绝', () => {
    expect(isSafeHttpUrl('file:///etc/passwd')).toBe(false)
    expect(isSafeHttpUrl('javascript:alert(1)')).toBe(false)
    expect(isSafeHttpUrl('magnet:?xt=urn:btih:abc')).toBe(false)
  })

  it('空串、超长与非字符串拒绝', () => {
    expect(isSafeHttpUrl('')).toBe(false)
    expect(isSafeHttpUrl('https://example.com/' + 'a'.repeat(8200))).toBe(false)
    expect(isSafeHttpUrl(42)).toBe(false)
    expect(isSafeHttpUrl(null)).toBe(false)
  })

  it('无法解析的地址拒绝', () => {
    expect(isSafeHttpUrl('https://')).toBe(false)
    expect(isSafeHttpUrl('not a url')).toBe(false)
  })
})

describe('嵌套结构的类型校验', () => {
  it('连接预设的协议白名单与结构校验', () => {
    const ok = sanitizeSettingsInput({
      connectionProfiles: [{ id: 'p', name: 'n', config: { host: 'h', port: 6800, protocol: 'ws', secret: '', path: '/jsonrpc' } }]
    })
    expect(ok.connectionProfiles?.[0]?.config.protocol).toBe('ws')
    expect(() => sanitizeSettingsInput({
      connectionProfiles: [{ id: 'p', name: 'n', config: { host: 'h', port: 6800, protocol: 'ftp', secret: '', path: '/jsonrpc' } }]
    })).toThrow()
    expect(() => sanitizeSettingsInput({ connectionProfiles: [{ id: 'p', name: 'n', config: 'nope' }] })).toThrow()
    expect(() => sanitizeSettingsInput({ connectionProfiles: [{ id: 'p', name: 'n' }] })).toThrow()
  })

  it('限速规则的时段与字段校验', () => {
    const ok = sanitizeSettingsInput({
      speedSchedule: {
        enabled: true,
        rules: [{ name: 'n', days: [0, 6], startTime: '00:00', endTime: '23:59', downloadLimit: 1024, uploadLimit: 0 }]
      }
    })
    expect(ok.speedSchedule?.rules[0]?.startTime).toBe('00:00')
    expect(() => sanitizeSettingsInput({ speedSchedule: { enabled: true, rules: ['nope'] } })).toThrow()
    expect(() => sanitizeSettingsInput({
      speedSchedule: { enabled: true, rules: [{ name: 'n', days: [1], startTime: '9:00', endTime: '18:00', downloadLimit: 0, uploadLimit: 0 }] }
    })).toThrow()
    expect(() => sanitizeSettingsInput({
      speedSchedule: { enabled: true, rules: [{ name: 'n', days: [7], startTime: '09:00', endTime: '18:00', downloadLimit: 0, uploadLimit: 0 }] }
    })).toThrow()
  })

  it('定时下载规则的条目校验', () => {
    const ok = sanitizeSettingsInput({
      downloadSchedule: {
        enabled: true,
        rules: [{ name: 'n', enabled: false, days: [1, 2], startTime: '01:00', endTime: '06:00' }]
      }
    })
    expect(ok.downloadSchedule?.rules[0]?.enabled).toBe(false)
    expect(() => sanitizeSettingsInput({ downloadSchedule: { enabled: true, rules: [42] } })).toThrow()
    expect(() => sanitizeSettingsInput({ downloadSchedule: { enabled: true, rules: [{ name: 'n', enabled: 'yes', days: [], startTime: '01:00', endTime: '06:00' }] } })).toThrow()
  })

  it('分类规则的可选字段与结构校验', () => {
    const ok = sanitizeSettingsInput({
      category: {
        autoClassify: true,
        categories: [{ id: 'c', dir: 'D:/a', extensions: ['.ZIP'], customDir: 'D:/b', name: '压缩包', custom: true }]
      }
    })
    expect(ok.category?.categories?.[0]).toEqual({ id: 'c', dir: 'D:/a', extensions: ['zip'], customDir: 'D:/b', name: '压缩包', custom: true })
    expect(() => sanitizeSettingsInput({ category: { categories: ['nope'] } })).toThrow()
    expect(() => sanitizeSettingsInput({ category: { categories: [{ id: 'c', dir: 'D:/a', extensions: ['zip'], custom: 'yes' }] } })).toThrow()
    expect(() => sanitizeSettingsInput({ category: 'nope' })).toThrow()
  })

  it('任务模板与完成规则的结构校验', () => {
    expect(() => sanitizeSettingsInput({ taskTemplates: ['nope'] })).toThrow()
    expect(() => sanitizeSettingsInput({ completionRules: ['nope'] })).toThrow()
    expect(() => sanitizeSettingsInput({
      completionRules: [{ id: 'r', name: 'n', enabled: true, actions: ['nope'] }]
    })).toThrow()
    expect(() => sanitizeSettingsInput({
      completionRules: [{ id: 'r', name: 'n', enabled: true, actions: [{ type: 'webhook', url: '', method: 'PUT' }] }]
    })).toThrow()
    expect(() => sanitizeSettingsInput({
      completionRules: [{ id: 'r', name: 'n', enabled: true, actions: [], condition: 'nope' }]
    })).toThrow()
    expect(() => sanitizeSettingsInput({
      completionRules: [{ id: 'r', name: 'n', enabled: true, actions: [], condition: { status: 'paused' } }]
    })).toThrow()
  })

  it('webhook 允许空 URL（未配置时不发通知）与 GET 方法', () => {
    const ok = sanitizeSettingsInput({
      completionRules: [{ id: 'r', name: 'n', enabled: true, actions: [{ type: 'webhook', url: '', method: 'GET' }] }]
    })
    expect(ok.completionRules?.[0]?.actions[0]).toEqual({ type: 'webhook', url: '', method: 'GET' })
  })

  it('webConsole 的令牌与结构校验', () => {
    expect(() => sanitizeSettingsInput({ webConsole: { tokens: ['nope'] } })).toThrow()
    expect(() => sanitizeSettingsInput({ webConsole: { allowedIps: [42] } })).toThrow()
    expect(() => sanitizeSettingsInput({ webConsole: 'nope' })).toThrow()
    expect(() => sanitizeSettingsInput({ pluginMarket: 'nope' })).toThrow()
  })

  it('各分区不是对象时整包拒绝', () => {
    expect(() => sanitizeSettingsInput({ aria2: 'nope' })).toThrow()
    expect(() => sanitizeSettingsInput({ download: 'nope' })).toThrow()
    expect(() => sanitizeSettingsInput({ speedSchedule: 'nope' })).toThrow()
    expect(() => sanitizeSettingsInput({ downloadSchedule: 'nope' })).toThrow()
    expect(() => sanitizeSettingsInput({ bt: 'nope' })).toThrow()
  })

  it('downloadCompleteAction 的枚举校验', () => {
    expect(() => sanitizeSettingsInput({ downloadCompleteAction: 'explode' })).toThrow()
  })
})
