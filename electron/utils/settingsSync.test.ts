import { describe, expect, it } from 'vitest'
import type { AppSettings } from '../../src/shared/appSettings'
import {
  ALLOWED_SETTINGS_KEYS,
  SETTINGS_EXPORT_APP_ID,
  applySettingsImport,
  buildSettingsExport,
  redactSettings
} from './settingsSync'

// ── 编译期守护：白名单必须与 AppSettings 顶层键严格一一对应 ──
// 接口新增顶层键而忘了加白名单时，Missing 不是 never，下面的赋值会编译失败；
// 白名单里写了接口中不存在的键时，Extra 不是 never，同样编译失败。
type MissingKey = Exclude<keyof AppSettings, (typeof ALLOWED_SETTINGS_KEYS)[number]>
type ExtraKey = Exclude<(typeof ALLOWED_SETTINGS_KEYS)[number], keyof AppSettings>
const _noMissingKey: Record<MissingKey, true> = {}
const _noExtraKey: Record<ExtraKey, true> = {}

/** 一份"什么敏感字段都有值"的设置，作为各用例的基线 */
function fullSettings(): AppSettings {
  return {
    language: 'zh-CN',
    theme: 'dark',
    refreshInterval: 1000,
    autoConnect: true,
    minimizeToTray: true,
    aria2: {
      host: '127.0.0.1',
      port: 6800,
      secret: 'rpc-secret-value',
      secretAutogenerated: false,
      protocol: 'http',
      path: '/jsonrpc'
    },
    connectionProfiles: [
      {
        id: 'p1',
        name: '本机',
        config: { host: '127.0.0.1', port: 6800, protocol: 'http', secret: 'profile-secret', path: '/jsonrpc' }
      },
      {
        id: 'p2',
        name: '远端',
        config: { host: '10.0.0.2', port: 6800, protocol: 'https', secret: 'profile-secret-2', path: '/jsonrpc' }
      }
    ],
    activeProfileId: 'p1',
    download: { defaultDir: 'D:/Downloads', maxConcurrentDownloads: 5 },
    queue: { maxConcurrent: 3, retryEnabled: true },
    taskTemplates: [
      { id: 't1', name: '模板', cookie: 'session=abc', dir: 'D:/Downloads' }
    ],
    completionRules: [
      {
        id: 'r1',
        name: '通知',
        enabled: true,
        actions: [
          { type: 'notify', title: '完成' },
          { type: 'webhook', url: 'https://example.com/hook', method: 'POST', secret: 'hook-secret' }
        ]
      }
    ],
    webConsole: {
      enabled: true,
      port: 6802,
      token: 'console-token-value',
      tokens: [
        { id: 'k1', name: '手机', token: 'token-one', scopes: ['tasks:read'] },
        { id: 'k2', name: 'HA', token: 'token-two', scopes: ['admin'] }
      ],
      allowedIps: ['127.0.0.1']
    },
    pluginMarket: { enabled: true, registryUrl: 'https://example.com/registry.json' },
    trustedPluginPublishers: ['-----BEGIN PUBLIC KEY-----']
  }
}

describe('ALLOWED_SETTINGS_KEYS', () => {
  it('与 AppSettings 顶层键一致且无重复', () => {
    expect(_noMissingKey).toEqual({})
    expect(_noExtraKey).toEqual({})
    expect(new Set(ALLOWED_SETTINGS_KEYS).size).toBe(ALLOWED_SETTINGS_KEYS.length)
    expect(ALLOWED_SETTINGS_KEYS).toContain('aria2')
    expect(ALLOWED_SETTINGS_KEYS).toContain('webConsole')
  })
})

describe('redactSettings', () => {
  it('清空全部敏感字段，其余字段原样保留', () => {
    const redacted = redactSettings(fullSettings())

    expect(redacted.aria2?.secret).toBe('')
    expect(redacted.connectionProfiles?.map(p => p.config.secret)).toEqual(['', ''])
    expect(redacted.webConsole?.token).toBe('')
    expect(redacted.webConsole?.tokens?.map(t => t.token)).toEqual(['', ''])
    expect(redacted.taskTemplates?.[0]?.cookie).toBe('')
    const webhook = redacted.completionRules?.[0]?.actions[1]
    expect(webhook?.type === 'webhook' && webhook.secret).toBe('')

    // 非敏感字段不受影响
    expect(redacted.aria2?.host).toBe('127.0.0.1')
    expect(redacted.aria2?.secretAutogenerated).toBe(false)
    expect(redacted.language).toBe('zh-CN')
    expect(redacted.theme).toBe('dark')
    expect(redacted.webConsole?.tokens?.map(t => t.name)).toEqual(['手机', 'HA'])
    expect(redacted.webConsole?.allowedIps).toEqual(['127.0.0.1'])
    expect(redacted.connectionProfiles?.[1]?.config.host).toBe('10.0.0.2')
    expect(redacted.taskTemplates?.[0]?.dir).toBe('D:/Downloads')
    expect(redacted.completionRules?.[0]?.actions[0]).toEqual({ type: 'notify', title: '完成' })
    expect(redacted.trustedPluginPublishers).toEqual(['-----BEGIN PUBLIC KEY-----'])
  })

  it('保持结构存在（字段为空字符串而非被删除）', () => {
    const redacted = redactSettings(fullSettings())
    expect(redacted.aria2).toHaveProperty('secret')
    expect(redacted.connectionProfiles?.[0]?.config).toHaveProperty('secret')
    expect(redacted.webConsole?.tokens?.[0]).toHaveProperty('token')
  })

  it('不修改入参（深拷贝语义）', () => {
    const original = fullSettings()
    redactSettings(original)
    expect(original.aria2?.secret).toBe('rpc-secret-value')
    expect(original.webConsole?.tokens?.[0]?.token).toBe('token-one')
  })

  it('敏感字段本就是空/缺失时不报错', () => {
    expect(() => redactSettings({})).not.toThrow()
    expect(redactSettings({ aria2: { secret: '' } }).aria2?.secret).toBe('')
  })
})

describe('buildSettingsExport', () => {
  it('includeSecrets=true：保留真实密钥且 redacted=false', () => {
    const data = buildSettingsExport(fullSettings(), '1.3.7', true)
    expect(data.app).toBe(SETTINGS_EXPORT_APP_ID)
    expect(data.version).toBe('1.3.7')
    expect(data.redacted).toBe(false)
    expect(new Date(data.exportedAt).toISOString()).toBe(data.exportedAt)
    const settings = data.settings as unknown as AppSettings
    expect(settings.aria2?.secret).toBe('rpc-secret-value')
    expect(settings.webConsole?.token).toBe('console-token-value')
  })

  it('includeSecrets=false：脱敏且 redacted=true', () => {
    const data = buildSettingsExport(fullSettings(), '1.3.7', false)
    expect(data.redacted).toBe(true)
    const settings = data.settings as unknown as AppSettings
    expect(settings.aria2?.secret).toBe('')
    expect(settings.connectionProfiles?.[0]?.config.secret).toBe('')
    expect(settings.webConsole?.tokens?.map(t => t.token)).toEqual(['', ''])
    expect(settings.language).toBe('zh-CN')
  })
})

describe('applySettingsImport 校验', () => {
  it('非对象数据报错', () => {
    const result = applySettingsImport(fullSettings(), 'not-an-object')
    expect(result.ok).toBe(false)
    if (!result.ok) expect(result.error).toContain('对象')
  })

  it('app 字段不是 Aria2Desktop 报错', () => {
    const result = applySettingsImport(fullSettings(), { app: 'OtherApp', settings: {} })
    expect(result.ok).toBe(false)
    if (!result.ok) expect(result.error).toContain('Aria2Desktop')
  })

  it('缺少 settings 对象报错', () => {
    const result = applySettingsImport(fullSettings(), { app: SETTINGS_EXPORT_APP_ID })
    expect(result.ok).toBe(false)
    if (!result.ok) expect(result.error).toContain('settings')
  })
})

describe('applySettingsImport 合并', () => {
  it('白名单外的键进 skipped，白名单内的进 applied 并浅覆盖', () => {
    const current = fullSettings()
    const result = applySettingsImport(current, {
      app: SETTINGS_EXPORT_APP_ID,
      version: '1.3.7',
      exportedAt: new Date().toISOString(),
      redacted: false,
      settings: {
        language: 'en-US',
        theme: 'light',
        unknownFutureKey: { a: 1 },
        anotherUnknown: 1
      }
    })

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.report.applied.sort()).toEqual(['language', 'theme'])
    expect(result.report.skipped.sort()).toEqual(['anotherUnknown', 'unknownFutureKey'])
    expect(result.report.rejected).toEqual([])
    expect(result.next.language).toBe('en-US')
    expect(result.next.theme).toBe('light')
    // 未出现在导出文件里的键保持本地值
    expect(result.next.aria2?.secret).toBe('rpc-secret-value')
    expect(result.next.webConsole?.token).toBe('console-token-value')
  })

  it('顶层键整键替换（不是深合并）', () => {
    const current = fullSettings()
    const result = applySettingsImport(current, {
      app: SETTINGS_EXPORT_APP_ID,
      settings: { webConsole: { enabled: false } }
    })

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.next.webConsole).toEqual({ enabled: false })
    expect(result.next.webConsole?.token).toBeUndefined()
  })

  it('非法 theme 值被 rejected 且不写入', () => {
    const current = fullSettings()
    const result = applySettingsImport(current, {
      app: SETTINGS_EXPORT_APP_ID,
      settings: { theme: 'neon', language: 'ja-JP' }
    })

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.report.rejected).toHaveLength(1)
    expect(result.report.rejected[0]?.key).toBe('theme')
    expect(result.report.rejected[0]?.reason).toContain('light')
    expect(result.report.applied).toEqual(['language'])
    expect(result.next.theme).toBe('dark')
    expect(result.next.language).toBe('ja-JP')
  })

  it('类型不符的 refreshInterval / webConsole / connectionProfiles 被 rejected', () => {
    const result = applySettingsImport(fullSettings(), {
      app: SETTINGS_EXPORT_APP_ID,
      settings: { refreshInterval: '1000', webConsole: 'nope', connectionProfiles: {} }
    })

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.report.applied).toEqual([])
    expect(result.report.rejected.map(r => r.key).sort()).toEqual(['connectionProfiles', 'refreshInterval', 'webConsole'])
    expect(result.report.rejected.every(r => r.reason.length > 0)).toBe(true)
  })

  it('不修改 current 入参', () => {
    const current = fullSettings()
    applySettingsImport(current, { app: SETTINGS_EXPORT_APP_ID, settings: { language: 'en-US' } })
    expect(current.language).toBe('zh-CN')
  })
})

describe('applySettingsImport 脱敏保护', () => {
  it('redacted 导入时保留本地密钥并计数', () => {
    const current = fullSettings()
    const exported = buildSettingsExport(fullSettings(), '1.3.7', false)

    const result = applySettingsImport(current, exported)
    expect(result.ok).toBe(true)
    if (!result.ok) return

    // aria2.secret + 2 条连接预设 secret + webConsole.token + 2 条 token
    // + 1 条 webhook secret + 1 条模板 cookie = 8
    expect(result.report.preservedSecrets).toBe(8)
    expect(result.next.aria2?.secret).toBe('rpc-secret-value')
    expect(result.next.connectionProfiles?.map(p => p.config.secret)).toEqual(['profile-secret', 'profile-secret-2'])
    expect(result.next.webConsole?.token).toBe('console-token-value')
    expect(result.next.webConsole?.tokens?.map(t => t.token)).toEqual(['token-one', 'token-two'])
    const webhook = result.next.completionRules?.[0]?.actions[1]
    expect(webhook?.type === 'webhook' && webhook.secret).toBe('hook-secret')
    expect(result.next.taskTemplates?.[0]?.cookie).toBe('session=abc')
  })

  it('本地密钥为空时不被"保留"（计数不增加）', () => {
    const current: AppSettings = { aria2: { secret: '' } }
    const exported = buildSettingsExport({ aria2: { secret: 'local' } }, '1.3.7', false)

    const result = applySettingsImport(current, exported)
    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.report.preservedSecrets).toBe(0)
    expect(result.next.aria2?.secret).toBe('')
  })

  it('未脱敏导入时空字符串会真的清空本地密钥（用户的显式选择）', () => {
    const current = fullSettings()
    const result = applySettingsImport(current, {
      app: SETTINGS_EXPORT_APP_ID,
      redacted: false,
      settings: { aria2: { host: '127.0.0.1', port: 6800, secret: '' } }
    })

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.report.preservedSecrets).toBe(0)
    expect(result.next.aria2?.secret).toBe('')
  })

  it('redacted 缺失（老文件）按未脱敏处理', () => {
    const current = fullSettings()
    const result = applySettingsImport(current, {
      app: SETTINGS_EXPORT_APP_ID,
      settings: { aria2: { secret: '' } }
    })

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.report.preservedSecrets).toBe(0)
    expect(result.next.aria2?.secret).toBe('')
  })
})
