/**
 * AppSettings 单一事实来源（主进程与渲染层共用）。
 *
 * 历史背景：此前主进程（electron/types/store.ts）与渲染层（src/services/settingsService.ts）
 * 各自维护一份 AppSettings 接口，要求"改一处同步另一处"，极易分叉。
 * 现在统一导入本文件的定义，任一侧新增字段只改这里。
 *
 * 注意：本文件不得 import electron，否则会污染渲染层打包。
 * 所有字段为可选，主进程按 Partial 语义读取（settings.aria2 || {}），
 * 渲染层通过 defaultSettings / mergeWithDefaults 提供缺省值。
 */
export interface ConnectionProfileConfig {
  host: string
  port: number
  protocol: 'http' | 'https' | 'ws' | 'wss'
  secret: string
  path: string
}

export interface ConnectionProfile {
  id: string
  name: string
  config: ConnectionProfileConfig
}

/** 单条速度调度规则 */
export interface SpeedScheduleRule {
  /** 规则名称（如"工作时段限速"） */
  name: string
  /** 星期几生效（0=周日，1=周一...6=周六），空数组表示每天 */
  days: number[]
  /** 开始时间（HH:mm 格式，如 "09:00"） */
  startTime: string
  /** 结束时间（HH:mm 格式，如 "18:00"），跨午夜时 endTime < startTime */
  endTime: string
  /** 该时段的下载限速（字节/秒），0 表示无限制 */
  downloadLimit: number
  /** 该时段的上传限速（字节/秒），0 表示无限制 */
  uploadLimit: number
}

/** 新建任务模板：把常用代理/请求头/保存目录等一键复用 */
export interface TaskTemplate {
  id: string
  name: string
  /** 保存目录（空表示使用默认目录） */
  dir?: string
  /** 代理，例如 http://127.0.0.1:7890 或 socks5://127.0.0.1:1080 */
  proxy?: string
  userAgent?: string
  referer?: string
  cookie?: string
  /** 额外请求头，每行 "Key: Value" */
  headers?: string
  /** 分段数（aria2 -s） */
  split?: number
  /** 单服务器连接数（aria2 -x） */
  maxConnectionPerServer?: number
}

/** 完成动作规则中的单个动作 */
export type CompletionRuleAction =
  | { type: 'move'; targetDir: string }
  | { type: 'rename'; pattern: string }
  | { type: 'open' }
  | { type: 'notify'; title?: string; body?: string }
  | { type: 'webhook'; url: string; method?: 'POST' | 'GET' }
  | { type: 'extract' }

/** 下载完成后按条件自动执行的规则 */
export interface CompletionRule {
  id: string
  name: string
  enabled: boolean
  /** 条件之间是 AND 关系；留空表示匹配所有完成的任务 */
  condition?: {
    /** 分类 id（general/video/music/images/documents/compressed/programs 或自定义） */
    category?: string
    /** 文件扩展名（不含点，空数组表示不限） */
    extensions?: string[]
    /** 仅匹配成功或失败的任务 */
    status?: 'complete' | 'error'
  }
  actions: CompletionRuleAction[]
}

/** 队列 2.0 设置 */
export interface QueueSettings {
  /** 最大同时下载数（同步到 aria2 max-concurrent-downloads） */
  maxConcurrent?: number
  /** 失败自动重试 */
  retryEnabled?: boolean
  /** 最大重试次数 */
  retryMaxAttempts?: number
  /** 重试间隔（秒） */
  retryDelaySeconds?: number
}

/** Headless Web 控制台设置 */
export interface WebConsoleSettings {
  enabled?: boolean
  port?: number
  /** 访问令牌；为空时由主进程自动生成 */
  token?: string
  /** 允许访问的 IP/CIDR；空数组表示仅本机 127.0.0.1/::1 */
  allowedIps?: string[]
}

export interface AppSettings {
  // 常规设置
  language?: string
  theme?: 'light' | 'dark' | 'auto'
  refreshInterval?: number
  autoConnect?: boolean
  minimizeToTray?: boolean
  keepWindowState?: boolean
  autoLaunch?: boolean
  /** 下载全部完成后执行的操作：none=不操作，shutdown=关机，hibernate=休眠，close=关闭应用，open-folder=打开所在目录，open-file=打开最近完成的文件 */
  downloadCompleteAction?: 'none' | 'shutdown' | 'hibernate' | 'close' | 'open-folder' | 'open-file'
  /** 是否在窗口获得焦点时检测剪贴板中的下载链接（隐私敏感，默认关闭） */
  clipboardMonitorEnabled?: boolean

  // 连接设置（保留兼容，实际使用 profiles）
  aria2?: {
    host?: string
    port?: number
    secret?: string
    /**
     * secret 是否由应用自动生成（首次启动无密钥时自动生成随机值，见 Aria2Controller）。
     * 用户在设置页显式保存过密钥配置（含主动清空）后置 false，此后不再自动生成，
     * 避免覆盖用户"无密钥"的显式选择。
     */
    secretAutogenerated?: boolean
    protocol?: 'http' | 'https' | 'ws' | 'wss'
    path?: string
    autoStart?: boolean
    downloadDir?: string
    /** 内置引擎 RPC 启动项（与 aria2.conf 同步，供下次启动使用） */
    enableRpc?: boolean
    rpcAllowOriginAll?: boolean
    rpcListenAll?: boolean
    rpcSecure?: boolean
  }

  // 多连接配置预设
  connectionProfiles?: ConnectionProfile[]
  activeProfileId?: string

  // 下载设置
  download?: {
    defaultDir?: string
    maxConcurrentDownloads?: number
    maxConnectionPerServer?: number
    minSplitSize?: string
    autoStart?: boolean
    /** 下载完成后自动解压压缩包（zip/7z/tar 系；RAR 不支持） */
    autoExtract?: boolean
    /** 自动解压成功后删除原压缩包（移入回收站，可恢复） */
    autoDeleteArchive?: boolean
    /** 最近使用的保存目录（新建任务页快捷选择，最多 8 条，最新在前） */
    recentSaveDirs?: string[]
  }

  // 速度调度规则（按时段自动切换限速）
  speedSchedule?: {
    enabled: boolean
    rules: SpeedScheduleRule[]
  }

  // 定时下载（按时段自动暂停/恢复全部任务）
  downloadSchedule?: {
    enabled: boolean
    rules: Array<{
      name: string
      enabled: boolean
      /** 星期几生效（0=周日…6=周六），空数组表示每天 */
      days: number[]
      startTime: string
      endTime: string
    }>
  }

  // 分类下载设置
  category?: {
    /** 是否按文件类型自动分类到子目录 */
    autoClassify?: boolean
    /** 分类规则（结构固定：general + Video/Music/Images/Documents/Compressed/Programs，可编辑目录名与扩展名） */
    categories?: CategoryRule[]
  }

  // BT 设置
  bt?: {
    /** 启用 UPnP 端口映射（BT/DHT 端口自动映射到网关，提升 BT 连通性） */
    upnpEnabled?: boolean
  }

  // 队列 2.0
  queue?: QueueSettings

  // 新建任务模板
  taskTemplates?: TaskTemplate[]

  // 下载完成动作规则（按分类/扩展名/状态触发）
  completionRules?: CompletionRule[]

  // Headless Web 控制台
  webConsole?: WebConsoleSettings

  // 插件市场
  pluginMarket?: {
    enabled?: boolean
    /** 市场目录 JSON 地址；留空使用官方默认地址 */
    registryUrl?: string
  }

  /** 受信任的插件发布者公钥（PEM，Ed25519）。用于校验插件签名 */
  trustedPluginPublishers?: string[]
}

/** 单个分类规则。id 固定为系统预定义值，dir 为子目录名，extensions 为用户可编辑的扩展名集合 */
export interface CategoryRule {
  /** 分类标识：general | video | music | images | documents | compressed | programs；自定义规则为生成值 */
  id: string
  /** 子目录名（英文），general 为空字符串表示不归入子目录 */
  dir: string
  /** 匹配的文件扩展名（不含点，小写），空数组表示无匹配 */
  extensions: string[]
  /**
   * 自定义完整目标目录（可选）。为空时：
   * - general 落到主下载目录；其他分类落到 下载目录/子目录名
   * 设置了值则覆盖默认，直接使用该目录
   */
  customDir?: string
  /** 自定义规则的显示名（内置规则为空，用 i18n 文案展示） */
  name?: string
  /** 是否用户自定义规则（内置规则由系统提供，用户可删可改） */
  custom?: boolean
}
